#!/usr/bin/env python3
"""Generate/check wheel notices using the engine's locked-graph method.

The engine's authoritative notices are retained byte-for-byte as the prefix.
Every registry package compiled by the binding contributes all root
LICENSE/COPYING/UNLICENSE/NOTICE texts not already in the engine prefix.
A published crate without these files is accepted only when the canonical
engine prefix explicitly inventories that exact package/version/licence as
having no vendored files; it is never silently counted as having a text.
Root-lock membership alone is not coverage: PyO3 may compile a crate which
is locked but unbuilt by the engine. The actual normal+build graph owns this.
No hand-maintained dependency list; no parser or third-party source is read.
"""
import argparse
import os
from pathlib import Path
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[1]
ENGINE = ROOT.parent.parent
def notice_default():
    # Maturin relocates pyproject/python-source to the sdist root while
    # retaining the nested Rust manifest. Follow that declared owner, not
    # an assumed duplicate bindings/python/python tree.
    manifest = (ROOT / "Cargo.toml").resolve()
    for project in (ROOT, ENGINE):
        path = project / "pyproject.toml"
        if not path.is_file():
            continue
        config = tomllib.loads(path.read_text())["tool"]["maturin"]
        if (project / config.get("manifest-path", "Cargo.toml")).resolve() == manifest:
            return project / config["python-source"] / "oxblend/THIRD-PARTY-NOTICES.txt"
    raise RuntimeError("no owning maturin pyproject for binding manifest")

DEFAULT = notice_default()

def packages(path):
    return {(p["name"], p["version"]): p for p in tomllib.loads(path.read_text())["package"]}

def source(name, version):
    home = Path(os.environ.get("CARGO_HOME", Path.home() / ".cargo"))
    candidates = sorted((home / "registry/src").glob(f"*/{name}-{version}"))
    if not candidates:
        raise RuntimeError(f"missing cached licence source: {name} {version}")
    return candidates[0]

def texts(directory):
    out = []
    for p in sorted(directory.iterdir()):
        if p.name.lower().startswith(("license", "licence", "copying", "unlicense", "notice")):
            for f in sorted(p.rglob("*")) if p.is_dir() else [p]:
                if f.is_file():
                    out.append((str(f.relative_to(directory)), f.read_bytes()))
    return out

def compiled_graph(manifest):
    tree = subprocess.check_output(["cargo", "tree", "--manifest-path", str(manifest), "--offline", "--locked", "-e", "normal,build", "--prefix", "none", "--format", "{p}"], text=True)
    return {(name, version.removeprefix("v")) for name, version in
            (tuple(line.split()[:2]) for line in tree.splitlines() if line.strip())}

def generate():
    locked = packages(ROOT / "Cargo.lock")
    prefix = (ENGINE / "THIRD-PARTY-NOTICES").read_bytes()
    built = compiled_graph(ROOT / "Cargo.toml")
    canonical = compiled_graph(ENGINE / "Cargo.toml")
    if not canonical <= built:
        raise RuntimeError(f"binding lock changes canonical engine compiled packages: {sorted(canonical - built)}")
    out = prefix + b"\nPython binding additions\n=======================\nGenerated by bindings/python/scripts/notices.py from the binding Cargo.lock.\nAll vendored root licence texts are retained; declared expressions select terms.\nThe engine prefix above is unchanged, including its licence choices.\n"
    for name, version in sorted(built):
        p = locked[(name, version)]
        if not p.get("source", "").startswith("registry+"):
            continue
        directory = source(name, version)
        files = texts(directory)
        declared = tomllib.loads((directory / "Cargo.toml").read_text())["package"]["license"]
        if not files:
            # Cargo publishes some workspace helper crates without licence
            # files. Reuse the already-reviewed engine inventory explicitly;
            # neither root-lock membership nor another crate's MIT text is
            # enough to invent coverage for a missing package declaration.
            inventory = f"\n{name} {version}\nDeclared licence: {declared}\nVendored licence files: none\n".encode()
            if inventory not in prefix:
                raise RuntimeError(f"no vendored licence text or canonical engine declaration: {name} {version}")
            continue
        if all(body in prefix for _, body in files):
            continue
        out += f"\n=== {name} {version} ===\nDeclared licence: {declared}\n".encode()
        for filename, body in files:
            out += f"\n--- {filename} ---\n".encode() + body + b"\n"
    checked = 0
    for name, version in sorted(built):
        p = locked[(name, version)]
        if not p.get("source", "").startswith("registry+"):
            continue
        for filename, body in texts(source(name, version)):
            if body not in out:
                raise RuntimeError(f"compiled crate licence absent: {name} {version}/{filename}")
        checked += 1
    return prefix, out, checked

def main():
    p = argparse.ArgumentParser()
    p.add_argument("action", choices=("generate", "check"))
    p.add_argument("--notices", type=Path, default=DEFAULT)
    a = p.parse_args()
    prefix, expected, count = generate()
    if a.action == "generate":
        a.notices.parent.mkdir(parents=True, exist_ok=True)
        a.notices.write_bytes(expected)
    else:
        actual = a.notices.read_bytes()
        if not actual.startswith(prefix):
            raise SystemExit("FAIL: engine notice prefix diverged")
        if actual != expected:
            raise SystemExit("FAIL: locked compiled-crate notices missing or stale; regenerate")
    print(f"PASS: {count} compiled registry packages covered by vendored texts or explicit engine no-file declarations; engine prefix exact")

if __name__ == "__main__":
    main()
