#!/usr/bin/env python3
"""Render shared guidance/catalog. --check refuses generated-surface drift."""
import argparse
import importlib.util
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def render(check=False, binary=None):
    spec = importlib.util.spec_from_file_location('stability', ROOT/'scripts/check-stability.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    kinds = module.inventory(ROOT)[1]
    catalog = json.loads((ROOT/'docs/error-catalog.json').read_text())
    entries = catalog['entries']
    declared = [e['kind'] for e in entries]
    if len(declared) != len(set(declared)) or set(declared) != kinds:
        raise SystemExit('error help drift: missing='+str(sorted(kinds-set(declared)))+' extra='+str(sorted(set(declared)-kinds)))
    for entry in entries:
        if not all(entry.get(k) for k in ('explanation', 'likely_causes', 'next_steps')):
            raise SystemExit('empty help: '+entry['kind'])
    guidance = json.loads((ROOT/'docs/guidance.json').read_text())
    outputs = {}
    docs = '# Known error kinds\n\nGenerated by scripts/generate-guidance.py from docs/error-catalog.json and docs/guidance.json.\nNo verified public issue mapping is implied.\n'
    docs += '\n## Accounted Python admission difference\n\n' + guidance['text']['python_nonregular_sources'] + '\n'
    for e in entries:
        docs += '\n<a id="error-'+e['kind']+'"></a>\n## `'+e['kind']+'`\n\n'+e['explanation']+'\n\nLikely causes: '+'; '.join(e['likely_causes'])+'\n\nNext: '+'; '.join(e['next_steps'])+'\n'
    outputs[ROOT/'docs/KNOWN-ISSUES.md'] = docs
    rust = '// Generated; edit docs/guidance.json, then scripts/generate-guidance.py.\n'
    for key, value in guidance['text'].items():
        # Documentation-only guidance has no compiled CLI consumer.
        if key not in guidance['help_surfaces']:
            continue
        rust += 'pub const '+key.upper()+': &str = '+json.dumps(value, ensure_ascii=False)+';\n'
    outputs[ROOT/'src/guidance.rs'] = subprocess.run(['rustfmt', '--emit', 'stdout'], input=rust, text=True, capture_output=True, check=True).stdout
    for relative, keys in guidance['surfaces'].items():
        path = ROOT/relative
        body = path.read_text()
        start, end = '<!-- generated-guidance -->', '<!-- /generated-guidance -->'
        generated = start+'\n'+'\n\n'.join(guidance['text'][k] for k in keys if k != 'diagnosis')+'\n'+end
        if start in body:
            body = body[:body.index(start)]+generated+body[body.index(end)+len(end):]
        else:
            body += '\n\n'+generated+'\n'
        if 'diagnosis' in keys:
            a, b = '<!-- generated-diagnosis -->', '<!-- /generated-diagnosis -->'
            diagnosis = a+'\n'+guidance['text']['diagnosis']+'\n'+b
            if a in body:
                body = body[:body.index(a)]+diagnosis+body[body.index(b)+len(b):]
            else:
                heading = re.search(r'^# [^\n]+\n', body, re.M)
                if not heading:
                    raise SystemExit('missing document heading: '+relative)
                body = body[:heading.end()]+'\n'+diagnosis+'\n'+body[heading.end():]
        outputs[path] = body
    drift = []
    for path, body in outputs.items():
        if not path.exists() or path.read_text() != body:
            if check:
                drift.append(str(path.relative_to(ROOT)))
            else:
                path.write_text(body)
    if drift:
        raise SystemExit('generated guidance drift: '+', '.join(drift))
    if binary is not None:
        commands = {}
        for key, targets in guidance['help_surfaces'].items():
            for command in targets:
                commands.setdefault(command, []).append(key)
        for command, keys in sorted(commands.items()):
            result = subprocess.run([str(binary.resolve()), command, '--help'], capture_output=True, text=True)
            if result.returncode:
                raise SystemExit(f'help consumer failed: {command}, exit {result.returncode}: {result.stderr}')
            for key in keys:
                if guidance['text'][key] not in result.stdout:
                    raise SystemExit(f'compiled guidance drift: {command} --help lacks shared {key}')
        print(f'CLI GUIDANCE PASS: {len(commands)} real command-help surfaces')
    print(f'GUIDANCE PASS: {len(entries)} exact-HEAD error kinds; shared wording surfaces synchronized')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--binary', type=Path, help='also verify the actual compiled help consumers')
    args = parser.parse_args()
    render(args.check, args.binary)
